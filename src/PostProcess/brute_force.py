import numpy as np
from qiskit_addon_opt_mapper.problems.optimization_problem import OptimizationProblem


def brute_force_max_cut(problem: OptimizationProblem) -> tuple[int, list[int]]:
    """Find the optimal Max-Cut solution by exhaustive enumeration.

    Iterates over all 2^n possible binary assignments and evaluates the
    cut value for each one. Used to verify the QAOA result on small instances.

    Args:
        problem: OptimizationProblem generated by Maxcut.to_optimization_problem().

    Returns:
        best_cut: Optimal cut value (integer).
        best_x:   Bitstring achieving the optimal cut, as a list of ints.
    """
    n = problem.get_num_vars()
    best_cut = -1
    best_x: list[int] = []

    for i in range(2**n):
        x = np.array([(i >> k) & 1 for k in range(n)])
        cut = problem.objective.evaluate(x)
        if cut > best_cut:
            best_cut = int(cut)
            best_x = x.tolist()

    return best_cut, best_x

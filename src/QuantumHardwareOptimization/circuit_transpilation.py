from pathlib import Path

from qiskit.circuit import QuantumCircuit
from qiskit.transpiler.preset_passmanagers import generate_preset_pass_manager
from qiskit_ibm_runtime import QiskitRuntimeService
from qiskit_ibm_runtime.ibm_backend import IBMBackend
from utils.config.env import qiskit_api_key, free_instance_crn
import matplotlib.pyplot as plt

OUTPUT_DIR = Path("output/figures")


def transpile_circuit(circuit: QuantumCircuit) -> tuple[QuantumCircuit, IBMBackend]:
    """Transpile the QAOA circuit to native IBM Quantum hardware instructions.

    Converts the abstract circuit into backend-native instructions:
      - Qubit mapping from virtual to physical
      - Gate decomposition to the hardware's native gate set
      - Routing according to the device topology
      - Circuit-level error suppression

    optimization_level=3 is the most aggressive preset: slower to transpile,
    but produces shorter circuits that are more robust to hardware noise.

    Args:
        circuit: Parametrized QAOA circuit generated by QAOAAnsatz.

    Returns:
        candidate_circuit: Transpiled circuit ready to execute on hardware.
        backend: Selected IBM Quantum backend.
    """
    # Connect to the service using credentials from utils/config/env.py
    service = QiskitRuntimeService(
        channel="ibm_cloud",
        token=qiskit_api_key,
        instance=free_instance_crn,
    )
    # Select the least busy backend with ≥127 qubits
    backend = service.least_busy(
        operational=True, simulator=False, min_num_qubits=127
    )
    print(f"    Backend selected: {backend}")

    # Create the pass manager and transpile the circuit
    pm = generate_preset_pass_manager(optimization_level=3, backend=backend)
    candidate_circuit = pm.run(circuit)

    # Save the transpiled circuit diagram to output/figures
    fig = candidate_circuit.draw("mpl", fold=False, idle_wires=False)
    OUTPUT_DIR.mkdir(parents=True, exist_ok=True)
    output_path = OUTPUT_DIR / "transpiled_circuit.png"
    fig.savefig(output_path, dpi=150, bbox_inches="tight")
    plt.close(fig)
    print(f"    Figure saved to: {output_path}")

    return candidate_circuit, backend
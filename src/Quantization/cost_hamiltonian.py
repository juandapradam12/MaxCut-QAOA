from qiskit.quantum_info import SparsePauliOp
from qiskit_addon_opt_mapper.converters import OptimizationProblemToQubo
from qiskit_addon_opt_mapper.translators import to_ising
from qiskit_addon_opt_mapper.problems.optimization_problem import OptimizationProblem


def build_cost_hamiltonian(maxcut_problem: OptimizationProblem) -> tuple[SparsePauliOp, float]:
    """Build the cost Hamiltonian H_C from the OptimizationProblem.

    Two-step process:
    1. Convert to QUBO with OptimizationProblemToQubo:
       - Turns the maximization into a minimization of the negated cut value.
    2. Translate the QUBO to an Ising Hamiltonian with to_ising:
       - Applies the substitution x_i → (1 - Z_i) / 2
       - Returns H_C as a SparsePauliOp and a scalar `offset` such that:
           QUBO_value = <H_C> + offset
         Therefore, the cut value of any bitstring is -(<H_C> + offset).

    For unweighted max-cut, the linear coefficients vanish (b_i = 0)
    and each edge (i, j) contributes the term (1/2) Z_i Z_j.

    Args:
        maxcut_problem: OptimizationProblem generated by Maxcut.to_optimization_problem().

    Returns:
        cost_hamiltonian: H_C as a SparsePauliOp.
        offset: Scalar offset to recover the cut value from the expectation value.
    """
    # Step 1: convert the optimization problem to QUBO form
    qubo = OptimizationProblemToQubo().convert(maxcut_problem)

    # Step 2: translate the QUBO to the Ising Hamiltonian H_C
    cost_hamiltonian, offset = to_ising(qubo)

    print("Cost function Hamiltonian:", cost_hamiltonian)
    print("Offset:", offset)

    return cost_hamiltonian, offset